"""Durable state for jobs executed by the browser-backed workers.

The XHS and Camoufox workers are deliberately stateless at the HTTP layer.  A
row here means a job can be looked up after a worker restart and that a late
browser result cannot accidentally be turned into a second publish request.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from sqlalchemy import JSON, DateTime, Index, Integer, String, Text, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, utcnow


class BrowserJobResult(Base):
    __tablename__ = "browser_job_results"
    __table_args__ = (
        UniqueConstraint("namespace", "job_id", name="uq_browser_job_results_namespace_job"),
        Index("ix_browser_job_results_recovery", "namespace", "state", "next_recovery_at"),
        Index("ix_browser_job_results_callback", "namespace", "state", "next_callback_at"),
    )

    # Job ids are generated by the caller and are also accepted by the worker
    # API.  A composite key keeps XHS and Camoufox namespaces independent.
    namespace: Mapped[str] = mapped_column(String(32), primary_key=True)
    job_id: Mapped[str] = mapped_column(String(64), primary_key=True)
    admin_id: Mapped[int | None] = mapped_column(Integer, nullable=True, index=True)
    # Only a one-way digest is kept.  Payloads can contain encrypted cookies
    # and must never be persisted in this table.
    fingerprint: Mapped[str] = mapped_column(String(128))
    state: Mapped[str] = mapped_column(String(24), default="running", server_default="running")
    data: Mapped[dict[str, Any]] = mapped_column(JSON, default=dict, server_default="{}")
    error: Mapped[str | None] = mapped_column(Text, nullable=True)
    worker_id: Mapped[str | None] = mapped_column(String(128), nullable=True)
    lease_expires_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    next_recovery_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    callback_attempts: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    next_callback_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    callback_delivered_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    completed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, onupdate=utcnow
    )
